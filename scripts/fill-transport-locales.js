function countStringKeys(obj, prefix = '') {
  let n = 0;
  if (!obj || typeof obj !== 'object') return 0;
  for (const [k, v] of Object.entries(obj)) {
    const pathKey = prefix ? `${prefix}.${k}` : k;
    if (typeof v === 'string') n += 1;
    else if (v && typeof v === 'object' && !Array.isArray(v)) n += countStringKeys(v, pathKey);
  }
  return n;
}

function fillLocale(code) {
  const file = path.join(UI_DIR, `${code}.json`);
  if (!fs.existsSync(file)) {
    console.warn(`skip missing file: ${code}`);
    return null;
  }
  const overlay = LOCALES[code];
  if (!overlay) {
    console.warn(`skip missing overlay: ${code}`);
    return null;
  }
  const enTransportKeys = Object.keys(require(path.join(UI_DIR, 'en.json')).transport);
  const missing = enTransportKeys.filter((k) => typeof overlay.transport?.[k] !== 'string');
  if (missing.length) {
    throw new Error(`${code}: missing transport keys: ${missing.join(', ')}`);
  }

  const current = JSON.parse(fs.readFileSync(file, 'utf8'));
  const next = deepMerge(current, overlay);
  fs.writeFileSync(file, `${JSON.stringify(next, null, 2)}\n`, 'utf8');

  return {
    code,
    transportKeys: Object.keys(overlay.transport).length,
    overlayStrings: countStringKeys(overlay),
  };
}

function main() {
  const summary = [];
  for (const code of SHORT_CODES) {
    const result = fillLocale(code);
    if (result) {
      summary.push(result);
      console.log(
        `${result.code}: wrote ${result.transportKeys} transport keys (${result.overlayStrings} overlay strings)`
      );
    }
  }
  clearUiMessagesCache();
  console.log(`Done. ${summary.length} locale packs updated.`);
}

main();
