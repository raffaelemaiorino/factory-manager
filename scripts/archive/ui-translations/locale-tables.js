function finalize(table, code) {
  const out = { ...table };
  for (const k of keys) {
    if (typeof out[k] !== 'string') out[k] = en[k];
  }
  const fs = require('fs');
  const path = require('path');
  fs.writeFileSync(
    path.join(__dirname, `${code}.js`),
    `module.exports = ${JSON.stringify(out, null, 2)};\n`
  );
}

