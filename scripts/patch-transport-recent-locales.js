function main() {
  let updated = 0;
  for (const [code, transportPatch] of Object.entries(PATCHES)) {
    const file = path.join(UI_DIR, `${code}.json`);
    if (!fs.existsSync(file)) {
      console.warn(`skip missing ${code}.json`);
      continue;
    }
    const current = JSON.parse(fs.readFileSync(file, 'utf8'));
    const next = deepMerge(current, { transport: transportPatch });
    fs.writeFileSync(file, `${JSON.stringify(next, null, 2)}\n`, 'utf8');
    updated += 1;
    console.log(`updated ${code}`);
  }
  clearUiMessagesCache();
  console.log(`done: ${updated} locales`);
}

main();
