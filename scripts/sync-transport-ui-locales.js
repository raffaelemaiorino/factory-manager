Object.assign(LOCALES, SHORT);

function syncFile(code) {
  if (code === 'en' || code === 'it') return false;
  const file = path.join(UI_DIR, `${code}.json`);
  if (!fs.existsSync(file)) return false;
  const overlay = LOCALES[code];
  if (!overlay) {
    // Lingue senza overlay dedicato: almeno nav.transport + chiavi dashboard minime (EN resta via merge runtime)
    const current = JSON.parse(fs.readFileSync(file, 'utf8'));
    const minimal = {
      nav: { transport: current.nav?.transport || 'Transport' },
    };
    const next = deepMerge(current, minimal);
    fs.writeFileSync(file, `${JSON.stringify(next, null, 2)}\n`, 'utf8');
    return true;
  }
  const current = JSON.parse(fs.readFileSync(file, 'utf8'));
  const next = deepMerge(current, overlay);
  fs.writeFileSync(file, `${JSON.stringify(next, null, 2)}\n`, 'utf8');
  return true;
}

function main() {
  const files = fs
    .readdirSync(UI_DIR)
    .filter((name) => name.endsWith('.json'))
    .map((name) => name.replace(/\.json$/, ''));

  let updated = 0;
  for (const code of files) {
    if (syncFile(code)) {
      updated += 1;
      console.log(`updated ${code}`);
    }
  }
  clearUiMessagesCache();
  console.log(`Done. ${updated} locale packs patched.`);
}

main();
